"""
Campus Unlock — University & Program Seed Data
=================================================
This module holds the raw data consumed by seed.py's idempotent
get_or_create seeding functions. Keeping the data here (separate from
the seeding logic) lets seed.py stay small and lets this list grow
over time without touching the script itself.

Structure
---------
EXISTING_UNIVERSITY_DEFS / EXISTING_PROGRAM_DEFS
    The original 10 launch universities and their programs, unchanged
    from the original seed.py. Left exactly as they were so re-running
    the seed never modifies these rows (get_or_create only fills in
    defaults on first creation).

NEW_UNIVERSITY_DEFS / NEW_PROGRAM_DEFS
    ~98 additional universities added to build a production-ready
    launch catalog spanning Central, State, Private, Deemed, Open/
    Distance universities, IITs, NITs, and IIITs.

    Data-quality note: to avoid fabricating anything, every NEW
    university intentionally leaves "website", "ranking"
    (NIRF), "accreditation" (NAAC grade), and "established_year"
    as None. Only name, city, state, university_type and ownership —
    which are stable, publicly documented facts — are populated. These
    optional fields can be filled in later via the admin panel once
    verified data is available, without needing another seed pass.

    Each new university gets exactly one representative sample Program
    so cards render correctly; fees are intentionally left as None
    (displays as "On request" on university cards) rather than
    inventing a number, per the same no-fabrication rule.

UNIVERSITY_DEFS / PROGRAM_DEFS
    The combined lists seed.py actually iterates over.
"""

